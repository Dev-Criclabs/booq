import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { startCluster, type Cluster } from '../packages/db/src/testing/cluster';
import { createProductionDatabase } from '../packages/db/src/testing/harness';

// `pnpm run db:types` (F01-T36): builds a database from the migrations only and writes the shape of
// every table (the schemas public, platform, audit, app) to packages/db/src/generated/schema.ts.
// CI runs it and fails if the file in the repository is out of date. Uses BOOQ_TEST_DATABASE_URL
// if set, else starts a throwaway Postgres.
const OUT = 'packages/db/src/generated/schema.ts';
const SCHEMAS = ['app', 'audit', 'platform', 'public'];

const TS: Record<string, string> = {
  uuid: 'string', text: 'string', varchar: 'string', bpchar: 'string', bool: 'boolean',
  int2: 'number', int4: 'number', float4: 'number', float8: 'number',
  int8: 'string', numeric: 'string',                 // node-postgres returns these as strings
  timestamptz: 'string', timestamp: 'string', date: 'string', time: 'string', interval: 'string',
  jsonb: 'unknown', json: 'unknown',
};
const tsType = (udt: string): string => (udt.startsWith('_') ? `${TS[udt.slice(1)] ?? 'unknown'}[]` : TS[udt] ?? 'unknown');
const pascal = (s: string) => s.split('_').map((w) => w[0]!.toUpperCase() + w.slice(1)).join('');

async function main(): Promise<void> {
  let cluster: Cluster | undefined;
  try {
    if (!process.env.BOOQ_TEST_DATABASE_URL) {
      cluster = await startCluster();
      process.env.BOOQ_TEST_DATABASE_URL = cluster.adminUrl;
    }
    const db = await createProductionDatabase();
    try {
      const { rows } = await db.query(
        `select c.table_schema, c.table_name, c.column_name, c.udt_name, c.is_nullable = 'YES' as nullable, c.column_default is not null as has_default
           from information_schema.columns c
           join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name and t.table_type = 'BASE TABLE'
          where c.table_schema = any($1) and not (c.table_schema = 'app' and c.table_name = 'test_clock')
          order by c.table_schema, c.table_name, c.ordinal_position`,
        [SCHEMAS],
      );
      const tables = new Map<string, typeof rows>();
      for (const r of rows) {
        const key = `${r.table_schema}.${r.table_name}`;
        tables.set(key, [...(tables.get(key) ?? []), r]);
      }
      let out = '// GENERATED by `pnpm run db:types` (tools/db-types.run.ts). Do not edit; CI fails if it is out of date.\n';
      out += '// One interface per table, as the database returns a row. 64-bit integers and numerics are strings (node-postgres).\n\n';
      for (const [key, cols] of tables) {
        out += `export interface ${pascal(key.replace('.', '_'))} {\n`;
        for (const c of cols) out += `  ${c.column_name}: ${tsType(c.udt_name)}${c.nullable ? ' | null' : ''};\n`;
        out += '}\n\n';
      }
      out += 'export interface Tables {\n';
      for (const key of tables.keys()) out += `  '${key}': ${pascal(key.replace('.', '_'))};\n`;
      out += '}\n';
      mkdirSync(dirname(OUT), { recursive: true });
      writeFileSync(OUT, out);
      console.log(`db:types wrote ${OUT} (${tables.size} tables)`);
    } finally {
      await db.close();
    }
  } finally {
    await cluster?.stop();
  }
}
main().then(() => process.exit(0), (e) => { console.error(e); process.exit(1); });
