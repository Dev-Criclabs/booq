// TEXT-03 pass: explicit, reviewed substitutions for sample values that the
// generic detectors in lib.mjs cannot name on their own.
//
// Each key maps to "literal=name; literal=name". The literal is replaced in BOTH
// files and becomes {name}. Rules:
//   - A number is replaced at its first free occurrence, in the order listed.
//   - "a|b" gives one literal per language (English|Thai); the one found is used.
//   - "[[1]] hour" replaces only the part in double brackets and uses the rest as context.
//   - A leading ! also runs the rule before the generic pass (Thai "คอร์ต 10 ชั่วโมง" is not a court).
//   - Literals with letters or ":" or a currency sign run before the generic pass
//     (dates, times, courts, amounts); plain numbers run after it.
// Wording is never changed: only the sample value is swapped for a variable.
//
// Policy numbers are club settings, so they get setting names:
//   holdMinutes (BOOK-03), cancelHours (CANCEL-01), claimMinutes (CLASS-02),
//   noOfferHours (CLASS-02), maxHoursInRow (rest rule), bookingWindowDays (A16).
// Money variables are pre-formatted by the app from integer satang, with the
// baht sign and separators, so the sign is part of the variable.

